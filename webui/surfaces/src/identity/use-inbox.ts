'use client';
import { useRef, useState, useSyncExternalStore } from 'react';
import { useFrontendTranslation } from '@community-go/i18n';
import {
  useNotificationsPort,
  type NotificationItem,
} from '@community-go/plugin-framework/notifications';
import { useIdentityQuery } from './use-query';
import { useIdentityPort } from './context';
import type { ProductInboxQuery } from './model';
import { IdentityError } from './errors';

/** One presentation collection for the shell and full inbox; backend records remain unpersisted. */
export function useProductInbox(
  options: Readonly<{ query?: ProductInboxQuery; id?: string }> = {},
) {
  const port = useIdentityPort();
  const events = useNotificationsPort();
  const { t } = useFrontendTranslation();
  const local = useSyncExternalStore(
    (listener) => events.subscribe(listener),
    () => events.list(),
    () => events.list(),
  );
  const query = options.query ?? { q: '', category: 'all', read: 'all', page: 1, pageSize: 20 };
  const result = useIdentityQuery(
    `inbox:${JSON.stringify(query)}:${options.id ?? ''}`,
    async (service) => {
      const [access, page] = await Promise.all([service.access(), service.inboxPage(query)]);
      const detail =
        options.id && !local.some((item) => item.id === options.id)
          ? await service.readNotification(options.id.replace(/^product:/, ''))
          : null;
      return {
        access,
        items: detail ? [detail] : page.items,
        total: page.total,
        unread: page.unread,
      };
    },
  );
  const [failure, setFailure] = useState<IdentityError | null>(null);
  const [pending, setPending] = useState(false);
  const pendingRef = useRef(false);
  const remote: NotificationItem[] = (result.data?.items ?? []).map((item) => {
    const access = result.data?.access;
    const own = item.objectId === access?.user.id && !item.operation.startsWith('roles.');
    const role = item.operation.startsWith('roles.');
    const settings = item.operation === 'settings.update';
    const canNavigate =
      own ||
      access?.permissions.includes(settings ? 'settings.read' : role ? 'roles.read' : 'users.read');
    return {
      // Keep service IDs distinct from IDs generated by the application-event store.
      id: `product:${item.id}`,
      category: item.category,
      severity: 'notice',
      createdAt: new Date(item.createdAt).getTime(),
      read: item.read,
      title: t('management.notificationTitle', {
        operation: t(`management.operations.${item.operation}`),
        name: item.objectName,
      }),
      description: t('management.businessEvent'),
      ...(canNavigate
        ? {
            target: settings
              ? { routeId: 'system-settings' }
              : own
                ? { routeId: 'account' }
                : { routeId: role ? 'roles.detail' : 'users.detail', query: { id: item.objectId } },
          }
        : {}),
    };
  });
  const items = [...remote, ...local].sort(
    (a, b) => b.createdAt - a.createdAt || a.id.localeCompare(b.id),
  );
  async function markRead(ids: readonly string[]) {
    if (pendingRef.current || !ids.length) return;
    pendingRef.current = true;
    setPending(true);
    setFailure(null);
    try {
      const selection = new Set(ids);
      const remoteIds = (result.data?.items ?? [])
        .filter((item) => selection.has(`product:${item.id}`) && !item.read)
        .map((item) => item.id);
      // API writes use a bounded batch; confirmed chunks stay read if a later request fails.
      for (let index = 0; index < remoteIds.length; index += 200)
        await port.readNotifications(remoteIds.slice(index, index + 200));
      local
        .filter((item) => selection.has(item.id) && !item.read)
        .forEach((item) => events.markRead(item.id));
      result.reload();
    } catch (error) {
      setFailure(error instanceof IdentityError ? error : new IdentityError('unavailable'));
    } finally {
      pendingRef.current = false;
      setPending(false);
    }
  }
  return {
    items,
    remote,
    local,
    total: result.data?.total ?? 0,
    unread: (result.data?.unread ?? 0) + local.filter((item) => !item.read).length,
    loading: result.loading,
    error: result.error,
    failure,
    pending,
    reload: () => {
      setFailure(null);
      result.reload();
    },
    markRead,
    markAllRead: async () => {
      if (pendingRef.current) return;
      pendingRef.current = true;
      setPending(true);
      setFailure(null);
      const localIds = local.filter((item) => !item.read).map((item) => item.id);
      try {
        await port.readAllNotifications();
        localIds.forEach((id) => events.markRead(id));
        result.reload();
      } catch (error) {
        setFailure(error instanceof IdentityError ? error : new IdentityError('unavailable'));
      } finally {
        pendingRef.current = false;
        setPending(false);
      }
    },
  };
}
